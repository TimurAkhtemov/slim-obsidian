cases = []
i = 0
for n in range(1, 15):
    for c in json.loads((SRC / f"c{n}.json").read_text()):
        text = f"**Them:** {c[0]}\n\n**Me:** {c[1]}" if isinstance(c, list) else c
        lab = L.get(i, ([], [], "email or no number: nothing scored"))
        if lab[0] == AMB:
            row = {"ambiguous": True, "secrets": [], "ordinary": [], "note": lab[1]}
        else:
            for s, _ in lab[0]:
                assert s in text, (i, s)
            for o in lab[1]:
                assert o in text, (i, o)
            row = {"ambiguous": False, "secrets": [list(x) for x in lab[0]], "ordinary": lab[1], "note": lab[2]}
        cases.append({"id": f"h{i:03d}", "src": f"c{n}", "split": "dev" if i < 80 else "test", "text": text, **row})
        i += 1
assert i == 330, i
OUT.write_text(json.dumps(cases, indent=1, ensure_ascii=False) + "\n")
amb = sum(c["ambiguous"] for c in cases)
print(f"{i} cases, {amb} ambiguous, {sum(len(c['secrets']) for c in cases)} secrets, "
      f"{sum(len(c['ordinary']) for c in cases)} ordinary")
